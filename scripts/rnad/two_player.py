"""Perolat et al. 2206.15378 supplementary p29 Eqs (1)-(5).

Full-episode two-player V-trace; the acting player may change each step.
This is not single-agent V-trace and does not treat a simultaneous
commit order as information available to either player's Actor.
"""
from __future__ import annotations
import torch


def rnad_targets(steps, eta=0.2, rho_bar=1.0, c_bar=1.0):
    """Compute detached per-decision value and all-legal-action Q targets.

    Each accepted chronological step: actor (0/1), reward (two zero-sum
    scalars for the underlying original game), value (acting player's
    target-network value), pi / magnet (normalized LEGAL distributions),
    behavior_prob (logged probability at acceptance), action_index.
    Rewards are 0 except for terminal four-win Match at the last step.
    Implements DeepNash supplementary Eq (1)-(5), including r-hat and
    xi propagation across the OTHER player's actions. No bootstrap.
    """
    if not steps:
        raise ValueError("Empty complete Match trajectory")
    if eta < 0 or rho_bar <= 0 or c_bar <= 0:
        raise ValueError("Invalid RNAD correction parameters")
    vhat = [0.0, 0.0]
    vnext = [0.0, 0.0]
    rhat = [0.0, 0.0]
    xi = [1.0, 1.0]
    output = [None] * len(steps)
    for t in range(len(steps)-1, -1, -1):
        row = steps[t]
        seat = row["actor"]
        if seat not in (0, 1):
            raise ValueError("Invalid acting seat")
        pi = row["pi"].detach().flatten().to(dtype=torch.float64)
        magnet = row["magnet"].detach().flatten().to(dtype=torch.float64)
        action = row["action_index"]
        mu = float(row["behavior_prob"])
        if (pi.numel() < 1 or magnet.shape != pi.shape or
            not 0 <= action < pi.numel() or mu <= 0 or mu > 1 or
            not torch.isfinite(pi).all() or not torch.isfinite(magnet).all() or
            torch.any(pi <= 0) or torch.any(magnet <= 0) or
            abs(float(pi.sum())-1) > 1e-5 or
            abs(float(magnet.sum())-1) > 1e-5):
            raise ValueError("Illegal/missing policy or behavior probabilities")
        original_reward = row["reward"]
        if len(original_reward) != 2 or abs(sum(original_reward)) > 1e-6:
            raise ValueError("Expected two-player zero-sum rewards")
        ratio = float(pi[action])/mu
        logratio = torch.log(pi/magnet)
        taken = float(logratio[action])
        reg = [float(original_reward[0]), float(original_reward[1])]
        reg[seat] -= eta*taken
        reg[1-seat] += eta*taken
        if abs(sum(reg)) > 1e-8:
            raise AssertionError("Regularization broke zero-sum signs")
        other = 1-seat
        # Eq (1): the non-acting player's time does not advance;
        # accumulate corrected future rewards and reach ratio.
        rhat[other] = reg[other] + ratio*rhat[other]
        xi[other] *= ratio
        # Eq (2)-(4): evaluate the current acting player's V-trace.
        v = float(row["value"])
        if not (torch.isfinite(torch.tensor(v)) and
                abs(v) < 1e6):
            raise ValueError("Invalid target-network value")
        prev_vhat = vhat[seat]
        corrected_ratio = ratio*xi[seat]
        rho = min(rho_bar, corrected_ratio)
        c = min(c_bar, corrected_ratio)
        delta = rho*(reg[seat] + ratio*rhat[seat] + vnext[seat] - v)
        value_target = v + delta + c*(prev_vhat-vnext[seat])
        # Eq (5): unchosen actions receive the regularizer; the
        # observed action additionally receives a 1/mu Q correction.
        q = -eta*logratio + v
        selected_correction = (
            reg[seat] + eta*taken +
            ratio*(rhat[seat]+prev_vhat) - v
        ) / mu
        q = q.clone()
        q[action] += selected_correction
        if not torch.isfinite(q).all() or not torch.isfinite(
            torch.tensor(value_target)):
            raise ValueError("Nonfinite two-player R-NaD target")
        output[t] = {"value_target": float(value_target),
                     "q_targets": q.to(dtype=torch.float32),
                     "rho": rho, "c": c, "ratio": ratio,
                     "actor": seat, "regularized_reward": tuple(reg)}
        vhat[seat] = value_target
        vnext[seat] = v
        rhat[seat] = 0.0
        xi[seat] = 1.0
    return output


def neurd_policy_loss(logits, q_targets, *, beta=2.0, q_clip=10.0,
                      logit_step=3e-4, is_c=1.0):
    """Stop-gradient Q and centered-logit NeuRD surrogate, NOT PPO.

    Parameter update follows the gradient in logit space proportional
    to centered all-action Q. The `beta` saturation threshold clips
    only outward-pushing updates, keeping interior corrections active.
    All passed candidates must have been generated by the game engine.
    """
    if (not 0 < logit_step <= 1 or beta < 0 or q_clip <= 0 or
        not isinstance(is_c, (int, float)) or
        not 0 <= is_c <= 1):
        raise ValueError("Invalid clipped NeuRD update scale")
    if logits.ndim != 1 or logits.shape != q_targets.shape or logits.numel() < 1:
        raise ValueError("Invalid all-legal-action NeuRD vectors")
    if not torch.isfinite(logits).all() or not torch.isfinite(q_targets).all():
        raise ValueError("Invalid nonfinite NeuRD logits/Q")
    q = q_targets.detach().to(logits).clamp(-q_clip, q_clip)
    probs = torch.softmax(logits.detach(), dim=-1)
    # DeepNash's clipped per-decision off-policy weight must also scale
    # the NeuRD force; the V-trace target alone does not correct this loss.
    advantage = (q - torch.sum(probs*q)) * is_c
    centered = logits-logits.mean()
    if beta > 0:
        # Tabular NeuRD clipping gate from the paper: allow a coordinate
        # only if its proposed centered logit stays inside [-beta,beta].
        # With a nonlinear shared NN and Adam this is a local surrogate,
        # NOT an exact projection of the full parameter-space update.
        proposed = centered.detach() + logit_step * advantage
        force = torch.where(proposed.abs() <= beta,
                            advantage, torch.zeros_like(advantage))
    else:
        force = advantage
    return -(centered*force).sum()/logits.numel()
